// Regenerates the procedural models bundled in assets/.
#include <cstdio>
#include <string>

#include "sr/mesh.hpp"

int main(int argc, char** argv) {
    std::string dir = argc > 1 ? argv[1] : SR_ASSET_DIR;
    sr::Mesh knot = sr::make_torus_knot(2, 3, 1.0f, 0.28f, 256, 32);
    sr::save_obj(knot, dir + "/torus_knot.obj", "(2,3) torus knot generated by tools/mkassets.cpp");
    std::printf("wrote %s/torus_knot.obj (%zu vertices, %zu triangles)\n", dir.c_str(), knot.vertices.size(),
                knot.triangle_count());
    return 0;
}
